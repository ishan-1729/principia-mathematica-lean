#!/usr/bin/env python3
"""Generate docs/PROPOSITIONS.md, the proposition map, from the Lean files.

Each proposition ✱N·M of data/principia.json must appear in `PrincipiaMathematica/Part*/` as a
docstring starting `/-- ✱N·M` immediately followed by the declaration `pmN_M`. Its status is the
`**Status.**` field of the docstring if present, otherwise `definition` for a Df and `proved` for
every other proposition. Each number ✱N has a unit block `## [✱N] Title` with its own status.

`--check` exits non-zero if a proposition or number is missing, still has a TODO, has no
declaration (or one with another name), or if a declaration of a `proved` proposition uses `sorry`.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATUSES = ('proved (reading)', 'proved (corrected)', 'proved', 'definition', 'remark', 'stated (open here)')
DOC = re.compile(r'/--\s*✱(\d+)·(\d+)(.*?)-/\s*\n((?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*'
                 r'(?:theorem|lemma|def|abbrev|instance|structure|inductive|class)\s+([^\s:(\[{]+))?', re.S)
UNIT = re.compile(r'/-!\s*\n## \[✱(\d+)\]\s*(.*?)\n(.*?)-/', re.S)


def main() -> int:
    sys.stdout.reconfigure(encoding='utf-8')
    check = '--check' in sys.argv
    data = json.loads((ROOT / 'data' / 'principia.json').read_text(encoding='utf-8'))
    expected = {}
    titles = {}
    for v in data['volumes']:
        for n in v['numbers']:
            titles[n['number']] = (v['volume'], n['title'])
            for p in n['propositions']:
                expected[p['n']] = (n['number'], p['kind'])
    found, units, problems = {}, {}, []
    for f in sorted((ROOT / 'PrincipiaMathematica').rglob('*.lean')):
        text = f.read_text(encoding='utf-8')
        rel = f.relative_to(ROOT).as_posix()
        for u in UNIT.finditer(text):
            st = re.search(r'\*\*Status\.\*\*\s*(.+)', u.group(3))
            units[int(u.group(1))] = (st.group(1).strip() if st else 'MISSING', rel)
        docs = list(DOC.finditer(text))
        for i, d in enumerate(docs):
            key = f'{d.group(1)}·{d.group(2)}'
            body = d.group(3)
            m = re.search(r'\*\*Status\.\*\*\s*([^\n]*)', body)
            status = None
            if m:
                s = m.group(1).strip()
                status = next((x for x in STATUSES if s.startswith(x)), 'INVALID: ' + s[:40])
            nxt = docs[i + 1].start() if i + 1 < len(docs) else len(text)
            seg = text[d.end():nxt]
            seg_code = re.sub(r'/-.*?-/', '', seg, flags=re.S)
            seg_code = re.sub(r'--[^\n]*', '', seg_code)
            found[key] = dict(status=status, decl=d.group(5), file=rel, todo='TODO(' in seg.split('/--')[0][:200] and d.group(5) is None,
                              sorry=re.search(r'\bsorry\b', seg_code) is not None)
    counts = {}
    rows = {}
    for key, (num, kind) in expected.items():
        name = 'pm' + key.replace('·', '_')
        r = found.get(key)
        if r is None:
            problems.append(f'✱{key}: no docstring')
            status = 'MISSING'
        else:
            status = r['status'] or ('definition' if kind == 'Df' else 'proved')
            if r['decl'] is None:
                problems.append(f'✱{key}: no declaration after the docstring (TODO?)')
                status = 'TODO'
            elif r['decl'] != name:
                problems.append(f'✱{key}: declaration is {r["decl"]}, expected {name}')
            if status.startswith('INVALID'):
                problems.append(f'✱{key}: {status}')
            if status.startswith('proved') and r['sorry']:
                problems.append(f'✱{key}: proved but uses sorry')
        counts[status] = counts.get(status, 0) + 1
        rows.setdefault(num, []).append((key, status))
    for num in titles:
        st = units.get(num, ('MISSING', ''))[0]
        if st == 'MISSING' or 'TODO' in st:
            problems.append(f'✱{num}: unit block status not filled')
    out = ['# Proposition map: *Principia Mathematica*, Volumes I and II', '',
           'Generated by `scripts/prop_table.py` from the Lean files. Do not edit by hand.', '',
           '| Status | Propositions |', '|---|---|']
    out += [f'| {k} | {v} |' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
    out += ['', f'Total: {len(expected)} numbered propositions in {len(titles)} numbers.', '',
            '| Number | Vol. | Title | Propositions | Not plainly `proved` | File |', '|---|---|---|---|---|---|']
    for num, (vol, title) in titles.items():
        rs = rows.get(num, [])
        special = [f'✱{k} ({s})' for k, s in rs if s not in ('proved', 'definition')]
        file = units.get(num, ('', ''))[1]
        out.append(f'| ✱{num} | {vol} | {title.capitalize()} | {len(rs)} | {", ".join(special) or "—"} | '
                   f'[{file.split("/", 1)[-1]}](../{file}) |')
    (ROOT / 'docs').mkdir(exist_ok=True)
    (ROOT / 'docs' / 'PROPOSITIONS.md').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(expected)} propositions; ' + ', '.join(f'{k}: {v}' for k, v in counts.items()))
    only = [a for a in sys.argv[1:] if not a.startswith('--')]
    shown = [p for p in problems if not only or any(o in p for o in only)]
    for p in shown[:200]:
        print('PROBLEM:', p)
    if len(shown) > 200:
        print(f'… {len(shown) - 200} more problems')
    return 1 if (check and problems) else 0


if __name__ == '__main__':
    sys.exit(main())
